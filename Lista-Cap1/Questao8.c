#include <stdio.h>  // biblioteca para funções de entrada e saída (como o printf)
#include <stdlib.h> // biblioteca para comandos do sistema (como o system)

int main()
{
    printf("\n\t\"Primeiro programa\""); // \n pula uma linha, \t dá um tab e \" coloca as aspas no texto
    system("PAUSE"); // pausa o programa e exibe "Pressione qualquer tecla para continuar..."
    return 0; // indica que o programa finalizou com sucesso
}

